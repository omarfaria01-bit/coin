"""Hours until a mint reaches ``min_coverage`` of the hourly index (#215).

Mirrors ``adapters.market_data.coverage``: the window is split into ``window // interval``
buckets and coverage is the share of buckets holding at least one sample. A mint that is
first sampled at t=0 fills one new bucket per successful sample, so it needs
``n = ceil(min_coverage * buckets)`` filled buckets. With miss rate ``m`` the expected number
of sampling slots is ``ceil(n / (1 - m))``; elapsed time is that many slots times the interval.

Pure and exact (``Fraction``): no clock, no network, no randomness. Expected value, not a
guarantee: with a real miss rate the true time varies around this figure.
"""

from __future__ import annotations

import json
import math
from fractions import Fraction
from pathlib import Path

INTERVALS_MIN = (5, 10, 15)
MISS_RATES = (Fraction(0), Fraction(1, 10), Fraction(3, 10))


def hours_to_eligible(
    interval_min: int,
    miss_rate: Fraction,
    min_coverage: Fraction,
    window_hours: int = 24,
) -> Fraction | None:
    """Expected hours until coverage >= ``min_coverage``; ``None`` if it never happens."""
    if interval_min < 1 or window_hours < 1:
        raise ValueError("interval_min and window_hours must be >= 1")
    if not 0 <= miss_rate <= 1:
        raise ValueError("miss_rate must be in [0, 1]")
    if not 0 <= min_coverage <= 1:
        raise ValueError("min_coverage must be in [0, 1]")
    buckets = max(1, window_hours * 60 // interval_min)
    needed = math.ceil(min_coverage * buckets)
    if needed == 0:
        return Fraction(0)
    if miss_rate == 1:
        return None
    slots = math.ceil(Fraction(needed) / (1 - miss_rate))
    # Cannot exceed the window: past `buckets` slots the oldest buckets would start to expire.
    if slots > buckets:
        return None
    return Fraction(slots * interval_min, 60)


def _fmt(h: Fraction | None) -> str:
    if h is None:
        return "never"
    tenths = math.floor(h * 10)  # floor, never round
    return f"{tenths // 10}.{tenths % 10}"


def render(min_coverage: Fraction, window_hours: int, sample_minutes: int) -> str:
    head = "| interval (min) | " + " | ".join(f"miss {m * 100:.0f}%" for m in MISS_RATES) + " |"
    lines = [
        "# Index coverage time (#215)",
        "",
        f"Hours until a mint has `min_coverage` = {min_coverage} of a {window_hours} h window "
        f"sampled (config interval: {sample_minutes} min). Expected value, floored to 0.1 h.",
        "Generated by `uv run python -m sim.index_coverage`; deterministic.",
        "",
        head,
        "|---|" + "---|" * len(MISS_RATES),
    ]
    for iv in INTERVALS_MIN:
        cells = [_fmt(hours_to_eligible(iv, m, min_coverage, window_hours)) for m in MISS_RATES]
        lines.append(f"| {iv} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Reading: the interval barely matters (only rounding to whole slots); the miss rate does.",
        "Eligibility also needs F1 age >= `min_age_hours` and F2-F11, so the top-10 stays empty",
        "at least this long after a mint is first sampled. Hourly runs see it up to 1 h later.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    p = json.loads((root / "index" / "params.json").read_text())
    n, d = p["min_coverage"].split("/")
    text = render(Fraction(int(n), int(d)), p["window_hours"], p["sample_minutes"])
    (root / "reports" / "index_coverage_table.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
